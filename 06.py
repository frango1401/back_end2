"""Exercício 10.

Conversão de Celsius para Fahrenheit
Desenvolva um programa que converta uma temperatura dada em Celsius para Fahrenheit.
Fórmula:
    F = C * 9 / 5 + 32
"""
temperatura = int(input("digite o a temperatura em celsius: "))
Fahrenheit = temperatura * 9 / 5 + 32

print(Fahrenheit)